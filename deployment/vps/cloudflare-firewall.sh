#!/usr/bin/env bash
# Allow only Cloudflare IP ranges to reach the web port, and teach Nginx to
# read the real client IP from CF-Connecting-IP.
#
# Usage (as root on the VPS):  deployment/vps/cloudflare-firewall.sh [PORT]
# Safe to re-run: it only touches ufw rules tagged with its own comment.
# Suggested cron (weekly):     0 4 * * 1 /root/miConnect/deployment/vps/cloudflare-firewall.sh >/var/log/cloudflare-firewall.log 2>&1
set -euo pipefail

PORT="${1:-28443}"
TAG="cloudflare-web-${PORT}"
REALIP_CONF="/etc/nginx/conf.d/cloudflare-realip.conf"

[ "$(id -u)" -eq 0 ] || { echo "Run as root" >&2; exit 1; }
command -v ufw >/dev/null || { echo "ufw not installed" >&2; exit 1; }

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$tmp/v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$tmp/v6"

# Sanity check: refuse to continue on an empty or malformed list, otherwise we
# would remove the old rules and lock Cloudflare (= all users) out.
grep -Eq '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' "$tmp/v4" || { echo "Bad IPv4 list" >&2; exit 1; }
grep -Eq '^[0-9a-f:]+/[0-9]{1,3}$' "$tmp/v6" || { echo "Bad IPv6 list" >&2; exit 1; }
v4_count=$(grep -Ec '^[0-9]' "$tmp/v4"); v6_count=$(grep -Ec '^[0-9a-f]' "$tmp/v6")
[ "$v4_count" -ge 5 ] && [ "$v6_count" -ge 3 ] || { echo "Suspiciously short list" >&2; exit 1; }

# 1) Remove previous rules carrying our tag (highest number first).
ufw status numbered | grep -F "# ${TAG}" | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn | while read -r n; do
  ufw --force delete "$n" >/dev/null
done

# 2) Add the current Cloudflare ranges.
for cidr in $(cat "$tmp/v4" "$tmp/v6"); do
  ufw allow from "$cidr" to any port "$PORT" proto tcp comment "$TAG" >/dev/null
done
echo "ufw: allowed ${v4_count} IPv4 + ${v6_count} IPv6 Cloudflare ranges on port ${PORT}"

# 3) Nginx real client IP (only trust the header from Cloudflare ranges).
if [ -d /etc/nginx/conf.d ]; then
  {
    echo "# Generated by cloudflare-firewall.sh on $(date -u +%F). Do not edit."
    for cidr in $(cat "$tmp/v4" "$tmp/v6"); do echo "set_real_ip_from ${cidr};"; done
    echo "real_ip_header CF-Connecting-IP;"
  } > "$tmp/realip.conf"
  install -m 0644 "$tmp/realip.conf" "$REALIP_CONF"
  if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx && echo "nginx: real IP config updated and reloaded"
  else
    echo "nginx -t failed; real IP config written but nginx NOT reloaded" >&2
    exit 1
  fi
fi
